-- Дата выкупа заказа на площадке.
--
-- Заказ CRM закрывается, как только Ozon отметил «везут»: работа у нас
-- кончилась. Но покупатель в этот момент товара ещё не видел — посылка
-- едет до пункта выдачи, и выкупают её днями позже. Просьба об отзыве
-- уходила через пять дней после закрытия, то есть по таймеру, а не по
-- событию: человеку, который ещё ничего не забрал, или наоборот — уже
-- неделю назад забравшему.
--
-- Теперь просьба идёт от этой даты. Пусто означает «ещё не выкупил»,
-- и ничего не отправляется.
--
-- IF NOT EXISTS: миграция должна проходить и на базе, где колонку
-- добавили руками.
ALTER TABLE "OrderPhoto" ADD COLUMN IF NOT EXISTS "marketplaceDeliveredAt" TIMESTAMP(3);

-- Индекс под фоновую сверку: она каждые 15 минут ищет маркетплейсные
-- заказы без отметки выкупа. Без индекса это перебор всей таблицы.
CREATE INDEX IF NOT EXISTS "OrderPhoto_isMarketplacePrint_marketplaceDeliveredAt_idx"
  ON "OrderPhoto" ("isMarketplacePrint", "marketplaceDeliveredAt");
