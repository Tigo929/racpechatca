-- Несколько складов по умолчанию в шаблоне карточек Ozon.
--
-- Остаток после публикации уходил на `warehouses[0]` — первый склад из
-- ответа площадки, молча и без выбора. У продавца с несколькими складами
-- товар оказывался доступен только в одном городе, и понять почему по
-- интерфейсу было нельзя: настройки складов там просто не было.
--
-- Храним warehouse_id площадки, а не ссылку на нашу строку OzonWarehouse:
-- именно его принимает API остатков, и он переживает пересборку снимка
-- складов. BIGINT — идентификаторы Ozon шестнадцатизначные.
--
-- Пустой список означает прежнее поведение. Это не заглушка, а осознанный
-- выбор: если считать пустоту за «все склады», то у продавца, который
-- ничего не настраивал, остаток внезапно уедет на все точки сразу.
ALTER TABLE "OzonCatalogTemplate"
  ADD COLUMN "defaultWarehouseIds" BIGINT[] NOT NULL DEFAULT ARRAY[]::BIGINT[];
