-- Корзина удалённых заказов: удаление становится обратимым на 30 дней.
--
-- До этой миграции OrderDeletion хранил только объяснение — номер, источник,
-- статус, сумму. Причину было видно, а вернуть ошибочно удалённый заказ
-- нельзя: позиции, история и начисления исчезали вместе с ним.
--
-- Почему снимок, а не флаг "deletedAt" у заказа: заказы читают около
-- девяноста запросов в тридцати модулях (зарплата, отчёты, аналитика,
-- Метрика, партнёр, листы согласования). Любой пропущенный "deletedAt IS
-- NULL" там вернул бы удалённый заказ в выручку или в чью-то зарплату, и
-- молча. Заказ по-прежнему удаляется физически, а вернуть его можно из
-- снимка.
ALTER TABLE "OrderDeletion"
    -- Полный заказ целиком: сам заказ, позиции (фото/футболки/холсты),
    -- история статусов, начисления. JSONB, а не колонки: состав заказа
    -- меняется каждый месяц, и схема архива не должна тянуться за ним.
    ADD COLUMN IF NOT EXISTS "snapshot"          JSONB,
    -- До этого момента заказ восстановим; дальше снимок вычищается, а
    -- запись о причине остаётся навсегда.
    ADD COLUMN IF NOT EXISTS "purgeAfter"        TIMESTAMP(3),
    ADD COLUMN IF NOT EXISTS "purgedAt"          TIMESTAMP(3),
    -- Восстановление — одноразовое: заполненный restoredAt закрывает запись.
    ADD COLUMN IF NOT EXISTS "restoredAt"        TIMESTAMP(3),
    ADD COLUMN IF NOT EXISTS "restoredById"      TEXT,
    ADD COLUMN IF NOT EXISTS "restoredByName"    TEXT,
    -- Ключ идемпотентности заявки с сайта. Сайт досылает недоставленную
    -- заявку до семи часов: без этой отметки повторная доставка завела бы
    -- заново ровно ту заявку, которую только что убрали руками.
    ADD COLUMN IF NOT EXISTS "externalRequestId" TEXT;

-- Воркер очистки ищет записи, которым вышел срок.
CREATE INDEX IF NOT EXISTS "OrderDeletion_purgeAfter_idx" ON "OrderDeletion"("purgeAfter");
-- Приём заявок проверяет «эту заявку уже удалили» на каждом лиде.
CREATE INDEX IF NOT EXISTS "OrderDeletion_externalRequestId_idx" ON "OrderDeletion"("externalRequestId");

-- Записи, сделанные до этой миграции, остаются без снимка: те заказы были
-- удалены физически и восстанавливать из них нечего. purgeAfter у них тоже
-- пуст — чистить нечего, а в списке они честно показываются как
-- «восстановление недоступно».
