-- Отметка о первом сообщении клиенту с сайта.
--
-- Бот Telegram написать первым не может: площадка разрешает ему отвечать
-- только тем, кто сам начал диалог. Поэтому первое сообщение отправляет
-- отдельный воркер от лица рабочего аккаунта, а очередь он берёт отсюда:
-- заявка сайта с телеграмом, у которой clientGreetedAt пуст.
--
-- Оба поля необязательные: у всех существующих заказов останется NULL,
-- и здороваться задним числом с теми, кто заказывал месяц назад, никто
-- не будет — воркер смотрит только на свежие заявки.
ALTER TABLE "OrderPhoto" ADD COLUMN "clientGreetedAt" TIMESTAMP(3);
ALTER TABLE "OrderPhoto" ADD COLUMN "clientGreetStatus" TEXT;

-- Индекс под запрос очереди: «не поздоровались, свежие, по дате».
CREATE INDEX "OrderPhoto_clientGreetedAt_createdAt_idx"
  ON "OrderPhoto" ("clientGreetedAt", "createdAt");
