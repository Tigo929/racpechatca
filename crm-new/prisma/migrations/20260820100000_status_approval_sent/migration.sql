-- «Отправлен на согласование» — второй шаг у футболок, сразу после «Новый».
-- Позицию в перечислении задаём явно (AFTER 'NEW'): порядок значений enum в
-- PostgreSQL участвует в сортировке, и новое значение не должно оказаться
-- в хвосте, за «Отменён».
--
-- IF NOT EXISTS — чтобы повторный прогон миграции не падал.
ALTER TYPE "EnumStatus" ADD VALUE IF NOT EXISTS 'APPROVAL_SENT' AFTER 'NEW';
