-- Прайс производства на холст: действует оптовый, а не розничный со скидкой.
--
-- Производство прислало оптовые цены (прайс от 24.09.2026), и оптовая цена
-- и есть то, сколько мы должны: скидка 20% была способом посчитать опт из
-- розницы, а не отдельной уступкой. Пока в настройках стоял RETAIL, долг
-- считался как розница минус 20% — для 20×30 это 504 ₽ против настоящих
-- 470 ₽, то есть себестоимость завышалась, а заработок занижался.
--
-- Режим влияет только на НОВЫЕ позиции: в сохранённых заказах лежат свои
-- числа, и задним числом они не пересчитываются. Переключить обратно —
-- одно поле в настройках CRM, выкладка для этого не нужна.
UPDATE "PartnerSettings"
SET "canvasPriceMode" = 'WHOLESALE'
WHERE "canvasPriceMode" = 'RETAIL';

ALTER TABLE "PartnerSettings"
ALTER COLUMN "canvasPriceMode" SET DEFAULT 'WHOLESALE';
