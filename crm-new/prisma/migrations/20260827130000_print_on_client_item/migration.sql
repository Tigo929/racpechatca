-- Печать на изделии заказчика как позиция со свободной ценой.
--
-- Такую работу заводят свободной позицией: цвета и размера у неё нет
-- (изделие принёс клиент), а сумма договорная и на количество не умножается.
-- Но в расчёте с партнёром она до сих пор не участвовала вовсе: settleOrder
-- читает только ItemTshirt, поэтому вознаграждение выходило нулевым, а вся
-- сумма попадала владельцу в прибыль. На заказе «3 изделия, 1500 ₽» это
-- расхождение в 597 ₽ — ровно те деньги, которые причитаются партнёру.
--
-- Признак ставится явно, а не выводится из названия: свободной позицией
-- заводят и кружку, и баннер, и их в расчёт с партнёром тянуть нельзя.
ALTER TABLE "ItemPhoto" ADD COLUMN "printOnClientItem" BOOLEAN NOT NULL DEFAULT false;

-- Снимок себестоимости термопереноса на момент оформления — как в ItemTshirt.
-- 0 у старых строк корректен: они не участвуют в расчёте (printOnClientItem=false).
ALTER TABLE "ItemPhoto" ADD COLUMN "thermalCost" INTEGER NOT NULL DEFAULT 0;
