-- Срок заказа в том виде, в каком его видно в списке.
--
-- Колонка `deadline` заполнена не у всех заказов: у восьмидесяти с лишним
-- фотозаказов её нет. Но пустой она означает не «без срока», а «срок по
-- умолчанию» — интерфейс и сервер одинаково считают его как дата создания
-- плюс три дня, и именно такой срок видит человек в столбце «Дедлайн».
--
-- Из-за этого сортировка по `deadline` врала: заказ, просроченный на шесть
-- дней, оказывался в самом конце списка «сначала ранние» — просто потому,
-- что в колонке было пусто, а пустые уходят вниз.
--
-- Считаем срок в самой базе, а не заполняем колонку задним числом:
-- вычисление остаётся вычислением и не превращается в выдуманные данные,
-- а изменится правило — изменится и выражение.
--
-- У футболок срока нет вовсе: их ведёт партнёр-исполнитель, и в списке
-- отсчёт для них не показывается. Пусто здесь означает ровно это.
ALTER TABLE "OrderPhoto"
  ADD COLUMN IF NOT EXISTS "deadlineEffective" TIMESTAMP(3)
  GENERATED ALWAYS AS (
    COALESCE(
      "deadline",
      CASE
        WHEN "productCategory" = 'TSHIRT' THEN NULL
        ELSE "createdAt" + INTERVAL '3 days'
      END
    )
  ) STORED;

-- IF NOT EXISTS: колонку завели на боевой базе до выкладки, проверяя
-- выражение на живых данных. Повторный проход миграции должен быть
-- тихим, а не падать на «колонка уже есть».

-- По этой колонке строится список заказов, когда выбран порядок по сроку.
CREATE INDEX IF NOT EXISTS "OrderPhoto_deadlineEffective_idx" ON "OrderPhoto"("deadlineEffective");
