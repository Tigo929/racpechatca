/**
 * Чат с покупателем в кабинете Ozon.
 *
 * Менеджер и так держит ссылку на переписку в заказе — он по ней отвечает
 * покупателю руками. В ссылке `https://seller.ozon.ru/app/messenger?id=<uuid>`
 * этот uuid и есть `chat_id`, которым Seller API принимает сообщение. Ничего
 * дополнительно спрашивать у человека не нужно: адресат уже записан.
 *
 * Здесь только разбор строки — ни сети, ни базы, поэтому правила проверяются
 * тестами целиком. Ошибиться тут дорого: чужой uuid означает согласование,
 * ушедшее не тому покупателю.
 */

/** uuid в том виде, в каком его выдаёт Ozon. */
const UUID =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * Идентификатор чата из того, что записано в заказе.
 *
 * Принимаем и ссылку из кабинета, и сам uuid: менеджеры копируют то одно,
 * то другое. Всё остальное — `null`, и отправка не начнётся: пустой ответ
 * честнее, чем догадка, кому писать.
 *
 * Параметр ищем строго `id`, а не «что-нибудь похожее на uuid в строке»:
 * в ссылке попадаются и другие идентификаторы (например, отправления), и
 * взять первый встретившийся значило бы писать в наугад выбранный чат.
 */
export function ozonChatId(value: string | null): string | null {
  const raw = (value ?? '').trim();
  if (!raw) return null;
  if (UUID.test(raw)) return raw.toLowerCase();

  // Ссылку разбираем целиком, а не регулярным выражением: у query-строки
  // есть свои правила (порядок, кодирование), и URL знает их лучше нас.
  let url: URL;
  try {
    url = new URL(raw.startsWith('http') ? raw : `https://${raw}`);
  } catch {
    return null;
  }
  // Чужой домен — не наш чат. Проверяем именно хвост имени, чтобы не
  // принять что-нибудь вроде `seller.ozon.ru.example.com`.
  const host = url.hostname.toLowerCase();
  if (host !== 'ozon.ru' && !host.endsWith('.ozon.ru')) return null;

  const id = (url.searchParams.get('id') ?? '').trim();
  return UUID.test(id) ? id.toLowerCase() : null;
}

/**
 * Имя файла, под которым лист согласования ляжет в переписку.
 *
 * Покупатель видит это имя в чате и по нему же сохраняет файл. Номер
 * заказа в имени — чтобы сохранённый макет можно было опознать через
 * неделю, когда в загрузках лежит десяток «image.jpg».
 */
export function ozonSheetFileName(
  orderNumber: string | number,
  version: number,
): string {
  const safe = String(orderNumber).replace(/[^\w-]+/g, '');
  return `maket-${safe || 'zakaz'}-v${version}.jpg`;
}
