/**
 * Своя ли это линейка — по началу артикула.
 *
 * В кабинете лежит несколько линеек, в CRM ведут одну, и список
 * отправлений показывает только её. Решает начало артикула: «papa-».
 *
 * Беда в том, что один и тот же артикул пишут по-разному. Русская
 * раскладка даёт «ПАПА-black-M», английская — «papa-black-M», а на
 * практике встречается и смесь: буквы «а», «р», «о», «с», «е», «х»
 * в двух алфавитах выглядят одинаково, и опечатку никто не замечает.
 * Для площадки это разные строки, для нас — одна линейка.
 *
 * Цена ошибки высокая: не узнали артикул — отправление пропало из списка,
 * заказ не заведён, футболка не напечатана, а площадка считает срок
 * отгрузки. Поэтому сравниваем не буквы, а то, как слово читается.
 */

/**
 * Кириллические буквы, которые пишут вместо латинских. Сюда же «п» и «р»:
 * в названии линейки они означают ту же «p», хотя и выглядят иначе —
 * «ПАПА» и «papa» для нас одно и то же слово.
 */
const LOOKALIKE: Record<string, string> = {
  а: 'a',
  в: 'b',
  е: 'e',
  к: 'k',
  м: 'm',
  н: 'h',
  о: 'o',
  п: 'p',
  р: 'p',
  с: 'c',
  т: 't',
  у: 'y',
  х: 'x',
};

/** Артикул в сравнимом виде: нижний регистр и латиница вместо похожих букв. */
export function normalizeArticle(value: string | null | undefined): string {
  return (value ?? '')
    .trim()
    .toLowerCase()
    .replace(/[а-яё]/g, (letter) => LOOKALIKE[letter] ?? letter);
}

/**
 * Начинается ли артикул с одного из начал линейки.
 *
 * Пустой список начал означает «показывать всё», а не «спрятать всё»:
 * фильтр по умолчанию не должен уметь оставлять человека без заказов.
 */
export function matchesLineup(
  offerId: string | null | undefined,
  prefixes: readonly string[],
): boolean {
  if (prefixes.length === 0) return true;
  const article = normalizeArticle(offerId);
  if (!article) return false;
  return prefixes.some((prefix) => {
    const normalized = normalizeArticle(prefix);
    return normalized.length > 0 && article.startsWith(normalized);
  });
}

/**
 * Какие линейки показывать в разделе маркетплейсов.
 *
 * В кабинете несколько линеек, а в CRM ведут одну — решение владельца
 * (02.10.2026). Остальные в списке только мешают искать нужное.
 *
 * Список здесь, а не в настройках, потому что меняется он раз в полгода,
 * а настройка потребовала бы экрана, хранения и миграции. Но помнить надо:
 * новая линейка не появится в списке сама — пока её префикс не добавлен
 * сюда, её заказы видно только по кнопке «Показать все».
 *
 * «custom» — без дефиса намеренно: линейка заведена в кабинете как
 * «Customer Black-1», и как именно её артикулы написаны — «custom-1-black-S»
 * или «customer-black-1-S» — решает карточка, а не мы. Общее начало слова
 * узнаёт оба написания; лишнего при этом не захватывает, потому что других
 * товаров на «custom» в кабинете нет.
 */
export const MARKETPLACE_ARTICLE_PREFIXES = ['papa-', 'custom'] as const;
