import { IsOptional, IsString, MaxLength } from 'class-validator';

/**
 * Что оператор добавляет к отправлению при заведении в CRM.
 *
 * Данные товара берутся из артикула, и трогать их нельзя. Единственное,
 * чего в отправлении нет, — ссылка на переписку: чат с покупателем живёт
 * в кабинете, и её оператор вставляет руками, если переписка началась.
 * Не вставил — контактом остаётся номер отправления.
 */
export class DtoCreateOzonCrmOrder {
  @IsOptional()
  @IsString()
  @MaxLength(500)
  chatUrl?: string;
}
