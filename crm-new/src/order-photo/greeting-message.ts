/**
 * Обращение целиком, а не только имя: у заявки имени может не быть,
 * а «Здравствуйте, !» читается как сбой, а не как вежливость.
 */
export function greetingFor(name: string | null | undefined): string {
  const clean = (name ?? '').trim();
  return clean ? `Здравствуйте, ${clean}!` : 'Здравствуйте!';
}

/**
 * Список позиций — по строке на позицию.
 *
 * Именно он отличает ответ на действие от рассылки: «Фото 10×15 с полями —
 * 10 шт.» невозможно спутать с массовой отправкой, потому что таких данных
 * у спамера нет.
 */
export function itemsList(items: GreetingItem[] | null | undefined): string {
  const rows: string[] = [];
  for (const item of items ?? []) {
    const title = (item?.title ?? '').trim();
    if (!title) continue;
    const quantity = Number(item?.quantity ?? 0);
    rows.push(quantity > 0 ? `• ${title} — ${quantity} шт.` : `• ${title}`);
  }
  return rows.length > 0 ? rows.join('\n') : '• уточним состав заказа в переписке';
}

/** Сумма с пробелами между разрядами: 2 490, а не 2490. */
export function money(total: number | null | undefined): string {
  const value = Math.trunc(Number(total ?? 0));
  if (!Number.isFinite(value) || value <= 0) return '—';
  return String(value).replace(/\B(?=(\d{3})+(?!\d))/gu, ' ');
}

/**
 * Строка доставки — своя для каждого способа.
 *
 * Пустую строку возвращать нельзя: в тексте останется дыра между списком
 * товаров и суммой, и человек прочтёт её как сбой. Поэтому у самовывоза
 * своя формулировка, а не отсутствие строки.
 */
export function deliveryLine(
  method: string | null | undefined,
  cost: number | null | undefined,
): string {
  const value = Math.trunc(Number(cost ?? 0));
  if (Number.isFinite(value) && value > 0) {
    return `🚚 Доставка Яндекс ПВЗ — ${money(value)} ₽`;
  }
  if ((method ?? '').toUpperCase() === 'YANDEX_PVZ') {
    /*
      Ноль у выбранного ПВЗ теперь означает бесплатную доставку: CRM
      обнуляет её сама, когда сумма позиций достаёт до порога. Раньше здесь
      стояло «стоимость уточним» — тогда ноль означал, что цену не проставили.
      Оставить ту формулировку значило бы пугать человека уточнением там, где
      он уже получил доставку в подарок.
    */
    return '🚚 Доставка Яндекс ПВЗ — бесплатно';
  }
  return '🏠 Самовывоз — бесплатно';
}

/** Готовый текст сообщения. Неизвестные метки остаются как есть. */
export function renderGreeting(data: GreetingData): string {
  const template = TEMPLATES[data.category] ?? TEMPLATES[''];
  return template
    .replace('{greeting}', greetingFor(data.name))
    .replace('{{СПИСОК_ТОВАРОВ}}', itemsList(data.items))
    .replace('{{ДОСТАВКА}}', deliveryLine(data.deliveryMethod, data.deliveryCost))
    .replace('{{СУММА}}', money(data.total))
    .replace('{{НОМЕР}}', data.numberOrder);
}
