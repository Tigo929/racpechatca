/**
 * Есть ли в заказе на футболки то, что исполнителю предстоит напечатать.
 *
 * До этого проверялось только наличие позиций-футболок, и заказ на печать по
 * изделию заказчика было не провести: футболку приносит клиент, мы наносим
 * принт — позиции-футболки в таком заказе нет по определению, и система
 * отвечала «В заказе нет позиций-футболок», не пуская его ни по статусам,
 * ни к исполнителю.
 *
 * Свободная позиция как раз для таких работ: у неё произвольное название и
 * договорная цена, а количество в сумму не умножается (см. order-pricing).
 * Поэтому наличие любой из двух разновидностей означает, что работа есть.
 *
 * Отдельным модулем, а не строкой на месте: та же проверка нужна и при смене
 * статуса, и при отправке исполнителю, и её легко забыть в одном из мест —
 * ровно так и вышло с первой версией.
 */
export interface OrderWithProductionItems {
  tshirtItems?: unknown[] | null;
  items?: unknown[] | null;
}

export function hasProductionItems(order: OrderWithProductionItems): boolean {
  return (order.tshirtItems?.length ?? 0) > 0 || (order.items?.length ?? 0) > 0;
}

/** Текст отказа — один на все места, чтобы подсказка была одинаковой. */
export const NO_PRODUCTION_ITEMS_MESSAGE =
  'В заказе нет ни одной позиции. Добавьте футболку или свободную позицию — ' +
  'например «Нанесение принта на изделие заказчика».';
