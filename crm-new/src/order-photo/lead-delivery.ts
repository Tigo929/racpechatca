import { EnumDeliveryMethod } from 'src/generated/prisma/enums';

/**
 * Стоимость доставки для заявки с сайта.
 *
 * Раньше заявка всегда создавалась с `deliveryCost: 0`, и доставку менеджер
 * дописывал руками при подтверждении. Пока переписка шла в мессенджере,
 * это было терпимо. Теперь клиенту сразу уходит сообщение с суммой — и она
 * обязана совпадать с тем, что он заплатит: назвать 1 350 ₽, а потом
 * добавить 300 ₽ хуже, чем сразу сказать 1 650 ₽.
 */

/**
 * Доставка в пункт выдачи Яндекса.
 *
 * Плоская цена: у нас один тариф независимо от города и веса заказа —
 * фотографии лёгкие, а разброс по тарифам площадки меньше, чем цена
 * времени менеджера на его выяснение.
 */
export const YANDEX_PVZ_DELIVERY_COST = 300;

/**
 * Сколько добавить к заказу за доставку.
 *
 * Самовывоз бесплатен, поэтому ноль здесь — не «не посчитали», а настоящая
 * цена. Неизвестный способ тоже даёт ноль: выдумывать доплату там, где
 * способ не распознан, значит завышать чек молча.
 */
export function leadDeliveryCost(method: EnumDeliveryMethod): number {
  return method === EnumDeliveryMethod.YANDEX_PVZ ? YANDEX_PVZ_DELIVERY_COST : 0;
}
