import type { EnumTshirtSize } from 'src/generated/prisma/enums';

/**
 * Размер футболки так, как его называют клиенту и производству.
 *
 * Буква и номер вместе: `S(46)`. На бирках изделий стоит российская
 * нумерация, а маркетплейсы в карточках показывают то же самое числом —
 * клиент видит «46» у себя в заказе и «S» в нашем макете, и это один
 * размер, а не два разных. Пара снимает вопрос целиком: ни клиенту, ни
 * печатнику не приходится держать таблицу в голове.
 *
 * Номера — та самая сетка, которой карточки уходят на Ozon
 * (`SIZE_TO_RUSSIAN_LABEL`): таблица здесь одна на всю систему, иначе
 * «размер в карточке» и «размер в макете» однажды разойдутся.
 */

/** Номер на бирке: российская сетка, шаг через размер. */
export const TSHIRT_SIZE_TAG: Record<EnumTshirtSize, string> = {
  XS: '44',
  S: '46',
  M: '48',
  L: '50',
  XL: '52',
  XXL: '54',
  XXXL: '56',
};

/**
 * Подпись размера для любого текста, который видит человек: макет на
 * согласование, сообщение клиенту, наклейка на пакет, задание печатнику.
 *
 * Буква берётся прямо из значения перечисления — она и есть название
 * размера, своего словаря ей не нужно.
 *
 * Строка на входе принимается наравне с перечислением: размер приходит и
 * из старых записей, и из нетипизированных выборок. Незнакомое значение
 * возвращаем как есть — подпись без номера лучше пустого места.
 */
export function tshirtSizeLabel(size: EnumTshirtSize | string): string {
  const tag = TSHIRT_SIZE_TAG[size as EnumTshirtSize];
  return tag ? `${size}(${tag})` : size;
}
