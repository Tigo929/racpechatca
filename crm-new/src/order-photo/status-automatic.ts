import { isMarketplaceTshirt } from './marketplace-tshirt';

/**
 * Статусы, которые система ставит сама — и поэтому руками не ставятся.
 *
 * Зачем запрет. Эти шаги и раньше проставлялись автоматически, но
 * оставались кликабельными, и нажать их мышкой было проще, чем сделать
 * то, что они означают. Результат: заказ числится переданным в
 * производство, а исполнитель о нём не знает; заказ «отгружен», а посылка
 * лежит на столе. Статус переставал быть фактом и становился намерением.
 *
 * Поэтому статус ставит только то событие, которое он описывает:
 *
 *   «Передан в производство» — отправка ТЗ исполнителю (нужны ТЗ-фото);
 *   «Отгружен»               — Ozon подтвердил, что посылка уехала.
 *
 * «В работе» здесь был и снят 31.10.2026. Посылка была та же — «его
 * ставит исполнитель кнопкой в Telegram», — но она не подтвердилась:
 * кнопку нажимали 3 раза, последний раз 3 сентября, а из панели этот
 * статус ставили людьми 391 раз. То есть запрет закрыл единственный
 * живой путь и оставил мёртвый. Прежде чем гасить шаг, нужно смотреть
 * не на то, что путь существует, а на то, что им пользуются.
 *
 * Запрет касается и администратора: владелец просил именно этого — чтобы
 * нельзя было щёлкнуть по ошибке. Застрявший заказ не заперт насовсем:
 * «Отменён» остаётся доступным, и выйти из тупика есть чем.
 *
 * Тот же вопрос решается на фронте (frontend/src/utils/status-automatic.ts),
 * и ответы обязаны совпадать: сервер не пускает, интерфейс гасит кнопку.
 */

export interface AutomaticStatusOrder {
  productCategory: string;
  isMarketplacePrint?: boolean | null;
}

export function automaticStatusError(
  order: AutomaticStatusOrder,
  next: string,
): string | null {
  const isTshirt = order.productCategory === 'TSHIRT';

  if (isTshirt && next === 'SENT') {
    return 'Этот статус ставится сам — когда заказ уходит исполнителю. Прикрепите ТЗ-фото и нажмите «Отправить ТЗ исполнителю».';
  }
  if (isMarketplaceTshirt(order) && next === 'COMPLETED') {
    return 'Этот статус ставится сам — когда Ozon отметит, что посылка уехала. Вручную отгрузку не подтверждаем.';
  }
  return null;
}
