import { isAffirmativeReply } from './client-reply';

/**
 * Что считается согласием.
 *
 * За этим правилом стоят деньги: на согласие клиенту уходит счёт, а заявка
 * становится заказом. Поэтому тесты сторожат не столько «узнаём ли мы да»,
 * сколько «не принимаем ли за да то, что им не является».
 */
describe('ответ клиента на приветствие', () => {
  it('чистое согласие узнаётся в разных написаниях', () => {
    for (const text of [
      'да',
      'Да',
      'ДА',
      'да!',
      'да.',
      'ага',
      'угу',
      'ок',
      'Окей',
      'ok',
      'хорошо',
      'конечно',
      'давайте',
      'Подтверждаю',
      'согласен',
      'согласна',
      'оформляйте',
      'беру',
      'заказываю',
      '+',
      'да 👍',
      'Да, всё верно',
      'да, оформляйте',
      'да, давайте',
      'хорошо, спасибо',
      'всё верно',
    ]) {
      expect(isAffirmativeReply(text)).toBe(true);
    }
  });

  it('уточнение и торг согласием не считаются', () => {
    for (const text of [
      'да, а можно 20 штук?',
      'да, но матовые',
      'да, только давайте завтра',
      'а сколько по времени?',
      'можно подешевле?',
      'нет',
      'не надо',
      'пока думаю',
      'здравствуйте',
      'я заказывал 50 фото, а тут 10',
      'да нет наверное',
    ]) {
      expect(isAffirmativeReply(text)).toBe(false);
    }
  });

  it('цифры в ответе отменяют согласие', () => {
    // Цифра почти всегда означает правку состава: тираж, размер, время.
    // Счёт на прежнюю сумму в ответ на такое — ошибка в деньгах.
    expect(isAffirmativeReply('да 20')).toBe(false);
    expect(isAffirmativeReply('да, 2 штуки')).toBe(false);
    expect(isAffirmativeReply('ок до 15')).toBe(false);
  });

  it('вопрос не согласие, даже если начинается с «да»', () => {
    expect(isAffirmativeReply('да?')).toBe(false);
    expect(isAffirmativeReply('да, а когда будет готово?')).toBe(false);
  });

  it('длинное сообщение читает человек', () => {
    expect(
      isAffirmativeReply(
        'да конечно оформляйте пожалуйста только аккуратнее с цветом',
      ),
    ).toBe(false);
  });

  it('пустота и мусор не согласие', () => {
    expect(isAffirmativeReply('')).toBe(false);
    expect(isAffirmativeReply('   ')).toBe(false);
    expect(isAffirmativeReply('👍')).toBe(false);
    expect(isAffirmativeReply('...')).toBe(false);
  });
});
