/**
 * Приветствия перестали уходить.
 *
 * Первое сообщение клиенту отправляет воркер от лица рабочего аккаунта:
 * бот Telegram написать первым не может, площадка ему этого не разрешает.
 * Значит, вся цепочка висит на одном живом аккаунте — а он отваливается:
 * отозвали сессию, упал контейнер, сменили пароль.
 *
 * И отваливается молча. Дважды подряд выяснялось это случайно, через
 * несколько дней, когда людям уже никто не ответил. Заявка в CRM при этом
 * лежит как обычно, и по ней не видно, что человеку не написали.
 *
 * Поэтому CRM смотрит на очередь со своей стороны: заявка с сайта,
 * телеграм, свежая — и всё ещё без приветствия спустя четверть часа.
 * Живой воркер отвечает за секунды, так что это означает ровно одно:
 * писать некому.
 */

/**
 * Сколько ждём, прежде чем считать, что воркер не работает.
 *
 * Живой воркер приветствует за секунды (по логам — 3–5). Четверть часа
 * с запасом покрывает и перезапуск контейнера, и паузу опроса, и
 * задержку самого Telegram.
 */
export const GREETING_STUCK_AFTER_MS = 15 * 60 * 1000;

/**
 * Как часто повторяем тревогу, пока она не снята.
 *
 * Сообщение раз в шесть часов читают. Сообщение каждые десять минут
 * выключают вместе со всеми остальными — и тогда следующий отказ опять
 * пройдёт незамеченным.
 */
export const GREETING_ALERT_REPEAT_MS = 6 * 60 * 60 * 1000;

export interface GreetingAlarmInput {
  /** Сколько заявок ждут приветствия дольше положенного. */
  stuck: number;
  /** Когда говорили об этом в прошлый раз. */
  lastAlertAt: Date | null;
  now: Date;
}

/**
 * Пора ли сказать владельцу, что приветствия не уходят.
 *
 * Очередь пуста — молчим и забываем прошлую тревогу: следующий отказ
 * должен прозвучать сразу, а не через шесть часов тишины.
 */
export function shouldAlertGreetingStuck(input: GreetingAlarmInput): boolean {
  if (input.stuck <= 0) return false;
  if (!input.lastAlertAt) return true;
  return (
    input.now.getTime() - input.lastAlertAt.getTime() >= GREETING_ALERT_REPEAT_MS
  );
}

/**
 * Текст тревоги.
 *
 * Номера заказов — главное в нём: по ним менеджер открывает карточку и
 * отправляет сообщение руками кнопкой «Скопировать сообщение клиенту».
 * Без номеров сообщение говорит «что-то сломалось» и не помогает никому.
 */
export function greetingStuckMessage(orders: string[]): string {
  const head =
    orders.length === 1
      ? '⚠️ Клиенту с сайта не ушло первое сообщение в Telegram.'
      : `⚠️ Клиентам с сайта не ушли первые сообщения в Telegram (${orders.length}).`;
  return [
    head,
    '',
    ...orders.map((number) => `• ${number}`),
    '',
    'Отправка идёт от рабочего аккаунта — похоже, он не в строю.',
    'Напишите людям вручную: в карточке заказа есть «Скопировать сообщение клиенту».',
  ].join('\n');
}
