/**
 * Ответ клиента на приветствие: согласие это или разговор.
 *
 * Зачем правило такое узкое. На согласие система отправляет счёт и переводит
 * заявку в заказ — сама, без человека. Ошибиться здесь дороже, чем промолчать:
 * «да, а можно 20 штук?» это не подтверждение прежнего состава, и счёт на
 * старую сумму в ответ на такой вопрос выглядит как невнимательность, за
 * которую клиент платит деньгами. Поэтому согласием считается только чистое
 * согласие, а всё остальное уходит человеку — он прочитает и ответит сам.
 *
 * Правило: сообщение состоит из слов согласия и вежливых добавок, в нём нет
 * ни цифр, ни вопроса, ни «но», и есть хотя бы одно слово, которое само по
 * себе означает «да».
 */

/** Слова, каждое из которых само по себе означает согласие. */
const CORE = new Set([
  'да',
  'дa', // латинская «a» — частая подмена при наборе с телефона
  'ага',
  'угу',
  'ок',
  'окей',
  'ok',
  'okay',
  'хорошо',
  'хорошо!',
  'конечно',
  'давай',
  'давайте',
  'подтверждаю',
  'согласен',
  'согласна',
  'оформляйте',
  'оформляй',
  'оформляем',
  'беру',
  'заказываю',
  'верно',
  'правильно',
  '+',
  'плюс',
]);

/**
 * Вежливые добавки: сами по себе ничего не подтверждают, но и не меняют
 * смысла. «Да, всё верно, спасибо» — то же согласие, что и «да».
 */
const FILLER = new Set([
  'все',
  'всё',
  'так',
  'точно',
  'именно',
  'пожалуйста',
  'спасибо',
  'отлично',
  'супер',
  'хорошо',
  'да',
]);

/** Длиннее этого сообщение — уже разговор, а не «да». */
const MAX_LENGTH = 40;

/**
 * Сообщение к сравнимому виду: без эмодзи, знаков препинания и регистра.
 * Плюс остаётся — им отвечают вместо «да».
 */
function normalize(text: string): string {
  return (text ?? '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^\p{L}\p{N}+\s]/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/** Чистое согласие — счёт можно отправлять. */
export function isAffirmativeReply(text: string): boolean {
  const raw = (text ?? '').trim();
  if (!raw || raw.length > MAX_LENGTH) return false;
  // Вопрос — это не согласие, даже если начинается с «да».
  if (raw.includes('?')) return false;
  // Цифры означают уточнение: тираж, размер, время. Состав мог поменяться,
  // и счёт на прежнюю сумму был бы неверным.
  if (/\d/.test(raw)) return false;

  const words = normalize(text).split(' ').filter(Boolean);
  if (words.length === 0 || words.length > 4) return false;

  let hasCore = false;
  for (const word of words) {
    if (CORE.has(word)) {
      hasCore = true;
      continue;
    }
    if (FILLER.has(word)) continue;
    // Любое слово вне обоих списков — уже разговор: «да, но», «да, только
    // матовые», «нет». Такое читает человек.
    return false;
  }
  return hasCore;
}
