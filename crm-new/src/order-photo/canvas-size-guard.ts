import { BadRequestException } from '@nestjs/common';
import { isListedCanvasSize } from 'src/canvas/canvas-production-price';

/**
 * Размер холста — только из прайса.
 *
 * Размер, вписанный словами, тянет за собой цену, вписанную руками: прайс
 * к такой позиции не применить, сверить её не с чем, и в финансовом отчёте
 * она даёт заработок, посчитанный от произвольного числа. У каждого размера
 * в прайсе две цены — розничная (её платит клиент) и оптовая (её платим мы);
 * разница между ними и есть заработок, и считать его можно только по
 * размеру, который в прайсе есть.
 *
 * Нестандартное — модульные холсты, нарезка, чужой подрамник — заводится
 * свободной позицией заказа: у неё для этого и есть своя цена.
 */
export function assertListedCanvasSize(sizeKey?: string | null): void {
  if (!isListedCanvasSize(sizeKey)) {
    throw new BadRequestException(
      'Размер холста выбирается из прайса производства: у каждого размера своя цена клиенту и своя цена производства. Нестандартное заведите свободной позицией.',
    );
  }
}
