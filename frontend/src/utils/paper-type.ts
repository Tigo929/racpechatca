/**
 * Цвет типа бумаги в интерфейсе: глянец и матт должны различаться с одного
 * взгляда, не читая подписи.
 *
 * Зачем: по умолчанию печатаем глянец, матовых заказов мало — и именно
 * поэтому матовый заказ легко напечатать «как обычно». Слово «Матт» серым
 * текстом в ряду таких же серых ячеек такую ошибку не останавливает, а
 * перепечатка стоит бумаги, времени и объяснений клиенту.
 *
 * Правило одно для всех мест, где тип бумаги виден: таблица позиций в
 * карточке и форма создания заказа. Расходиться им нельзя — фиолетовое в
 * одном месте и синее в другом учат не доверять цвету вообще.
 */

import { TYPE_LABELS } from '../constants';
import type { EnumTypePaper } from '../types/index';

export interface PaperTypeStyle {
  /** Подпись из общего словаря: «Глянец», «Матт». */
  label: string;
  /** Бейдж в ячейке «Тип» и в заголовке блока позиций. */
  badge: string;
  /** Фон строки позиции — то самое «подчеркнуть фоном». */
  row: string;
  /** Поле ввода (выпадающий список), когда тип уже выбран. */
  field: string;
}

/*
 * Синий у глянца, фиолетовый у матта.
 *
 * Фиолетовый громче — он достался исключению, а не норме: заливать им
 * девять строк из десяти значило бы снова не заметить десятую. Оба цвета
 * свободны внутри таблицы позиций: янтарный там занят пометкой «своб.»,
 * красный и зелёный — удалением и сохранением.
 */
export const PAPER_TYPE_STYLES: Record<EnumTypePaper, PaperTypeStyle> = {
  GLOSS: {
    label: TYPE_LABELS.GLOSS,
    badge: 'bg-sky-100 text-sky-800 ring-1 ring-sky-200',
    row: 'bg-sky-50 hover:bg-sky-100',
    field: 'bg-sky-50 text-sky-900',
  },
  MATTE: {
    /*
     * Заливка строки сильнее, а бейдж сплошной: бледная подложка на
     * проверке терялась среди глянцевых строк — ровно та ошибка, от
     * которой цвет и заведён.
     */
    label: TYPE_LABELS.MATTE,
    badge: 'bg-violet-600 text-white',
    row: 'bg-violet-100 hover:bg-violet-200',
    field: 'bg-violet-100 text-violet-900 font-semibold',
  },
};

/**
 * Позиция в том виде, в каком у неё есть тип бумаги.
 *
 * Количество сюда не входит намеренно: цвет нужен и строке таблицы, и
 * полю ввода в форме, а в поле ввода количество — строка, которую человек
 * ещё печатает. Для счётчика матовых снимков количество добавлено отдельно.
 */
export interface PaperItem {
  typePaper: string;
  isFreePrice?: boolean;
}

/** Позиция, по которой считают расход матовой бумаги. */
export interface CountedPaperItem extends PaperItem {
  quantity: number;
}

/**
 * Цвет типа бумаги для позиции — или null, если красить нечего.
 *
 * Свободная позиция — произвольный товар с названием и ценой: тип бумаги
 * у неё остаётся `GLOSS` только потому, что поле обязательно, и печатать
 * по нему никто ничего не будет. Покрасить её «глянцем» значит соврать,
 * поэтому в таблице у такой позиции стоит прочерк.
 */
export function paperTypeStyle(item: PaperItem): PaperTypeStyle | null {
  if (item.isFreePrice) return null;
  return PAPER_TYPE_STYLES[item.typePaper as EnumTypePaper] ?? null;
}

/**
 * Сколько снимков в заказе печатается на матовой бумаге.
 *
 * Нужно для подписи в заголовке позиций: заказ бывает смешанный, и по
 * одному цвету строк не видно, сколько именно бумаги готовить. Ноль —
 * подписи нет: пустое место честнее слов «матовых нет».
 */
export function mattePhotoCount(items: readonly CountedPaperItem[]): number {
  return items
    .filter((item) => !item.isFreePrice && item.typePaper === 'MATTE')
    .reduce((sum, item) => sum + Math.max(0, item.quantity ?? 0), 0);
}
