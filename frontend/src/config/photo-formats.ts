/**
 * Справочник форматов фотопечати.
 *
 * Формат вводили руками, и в базе накопилось больше тридцати написаний одного
 * и того же: «10х15», «10x15» латиницей, «10Х15», «паларойд», «паларод»,
 * «Инстакс». Пока формат не опознан, расход бумаги посчитать нельзя — а без
 * него оборот по фото выглядит чистым заработком.
 *
 * Список составлен по фактической статистике заказов: сверху то, что печатают
 * чаще всего. Поле осталось свободным — редкие форматы вписываются руками, и
 * расход по ним считается геометрией (см. utils/photo-material.ts).
 */

export interface PhotoFormatOption {
  /** То, что попадёт в заказ и в чек клиенту. */
  value: string;
  /** Сколько снимков выходит из листа 10×15 — для подсказки в интерфейсе. */
  perSheet: number;
}

/** Порядок — по частоте в заказах: самое ходовое первым. */
export const PHOTO_FORMATS: readonly PhotoFormatOption[] = [
  { value: '10×15 без полей', perSheet: 1 },
  { value: '10×15 с полями', perSheet: 1 },
  { value: '7,5×10 с полями', perSheet: 2 },
  { value: '7,5×10 без полей', perSheet: 2 },
  { value: 'Polaroid', perSheet: 2 },
  { value: 'Instax', perSheet: 2 },
  { value: '10×10 с полями', perSheet: 1 },
  { value: '4×4', perSheet: 6 },
];

/** Подсказка под полем: во что обойдётся лист при таком формате. */
export function sheetHint(perSheet: number): string {
  if (perSheet === 1) return 'целый лист на фото';
  return `${perSheet} фото с листа`;
}
